"""The data catalog (``data/catalog.json``): one entry per data source.

The catalog is *generated* by ``python -m martian_map snapshot`` and never
edited by hand. Every entry says what kind of evidence it is (the project
plan's shared requirement), where its files are or how to load it live, and
what it can't tell you.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from .http import atomic_write
from .scenario import Bounds

CATALOG_VERSION = 1
CATALOG_NOTE = (
    "Generated by python -m martian_map snapshot. Do not edit by hand; "
    "edit scenario/gale.json or the step code instead. "
    "The pipeline code was written with an AI coding assistant (Claude Code); "
    "no data values were generated by AI. Sources: see references and docs/data-references.md."
)
FACTORS = ("terrain", "ground", "solar", "thermal", "routes")
EVIDENCE_TYPES = ("observation", "derived", "model", "interpretation", "assumption", "reference")
ACCESS = ("local", "live", "computed", "not_used", "pending")
STATUS = ("ok", "failed", "not_downloaded")

_ID_RE = re.compile(r"^[a-z][a-z0-9_]{0,63}$")


class CatalogError(ValueError):
    """A catalog entry or file is invalid."""


def _defaults() -> Dict[str, Any]:
    return {
        "tags": [],
        "status": "ok",
        "files": [],
        "limitations": [],
        "uncertainty": {"value": "unknown"},
        "coverage": {},
        "source": {},
        "ground_validated": {"value": False, "note": ""},
        "resolution_m": None,
        "smallest_feature_m": None,
        "positional_accuracy": "unknown",
        "observation_time": {},
    }


def validate_entry(entry: Dict[str, Any]) -> None:
    eid = entry.get("id")
    if not isinstance(eid, str) or not _ID_RE.fullmatch(eid):
        raise CatalogError(f"dataset id {eid!r} must match {_ID_RE.pattern}")
    if not str(entry.get("title") or "").strip():
        raise CatalogError(f"{eid}: title must not be empty")
    if not str(entry.get("summary") or "").strip():
        raise CatalogError(f"{eid}: summary must not be empty")
    factors = entry.get("factors")
    if not isinstance(factors, list) or any(f not in FACTORS for f in factors):
        raise CatalogError(f"{eid}: factors {factors!r} must be a list drawn from {FACTORS}")
    if entry.get("evidence_type") not in EVIDENCE_TYPES:
        raise CatalogError(f"{eid}: evidence_type {entry.get('evidence_type')!r} not in {EVIDENCE_TYPES}")
    access = entry.get("access")
    if access not in ACCESS:
        raise CatalogError(f"{eid}: access {access!r} not in {ACCESS}")
    status = entry.get("status")
    if status not in STATUS:
        raise CatalogError(f"{eid}: status {status!r} not in {STATUS}")
    if access in ("not_used", "pending") and not str(entry.get("reason") or "").strip():
        raise CatalogError(f"{eid}: {access} entries need a reason")
    if access == "local" and status == "ok" and not entry.get("files"):
        raise CatalogError(f"{eid}: local entries with status ok need at least one file")


def new_entry(
    id: str,
    title: str,
    summary: str,
    factors: Sequence[str],
    category: str,
    evidence_type: str,
    access: str,
    **fields: Any,
) -> Dict[str, Any]:
    entry: Dict[str, Any] = {
        "id": id,
        "title": title,
        "summary": summary,
        "factors": list(factors),
        "category": category,
        "evidence_type": evidence_type,
        "access": access,
    }
    entry.update(_defaults())
    entry.update(fields)
    validate_entry(entry)
    return entry


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def file_record(path: Path, data_root: Path, fmt: str, **extra: Any) -> Dict[str, Any]:
    path = Path(path)
    rel = path.resolve().relative_to(Path(data_root).resolve()).as_posix()
    record: Dict[str, Any] = {"path": rel, "format": fmt, "bytes": path.stat().st_size, "sha256": _sha256(path)}
    record.update(extra)
    return record


def file_state(data_root: Path, rec: Dict[str, Any]) -> str:
    """'ok', 'not_downloaded' or 'different' for one file record."""
    p = Path(data_root) / rec["path"]
    if not p.is_file():
        return "not_downloaded"
    if p.stat().st_size != rec.get("bytes") or _sha256(p) != rec.get("sha256"):
        return "different"
    return "ok"


@dataclass(frozen=True)
class CheckResult:
    dataset_id: str
    path: str
    state: str


def _md_cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


@dataclass
class Catalog:
    entries: List[Dict[str, Any]]
    areas: Dict[str, Any] = field(default_factory=dict)
    generated_at: str = ""
    scenario_file: str = ""
    coverage_report: List[Dict[str, Any]] = field(default_factory=list)
    references: Dict[str, Any] = field(default_factory=dict)

    @classmethod
    def load(cls, path: Path) -> "Catalog":
        raw = json.loads(Path(path).read_text(encoding="utf-8"))
        if raw.get("version") != CATALOG_VERSION:
            raise CatalogError(f"{path}: unsupported catalog version {raw.get('version')!r}")
        return cls(
            entries=list(raw.get("datasets") or []),
            areas=dict(raw.get("areas") or {}),
            generated_at=str(raw.get("generated_at") or ""),
            scenario_file=str(raw.get("scenario_file") or ""),
            coverage_report=list(raw.get("coverage_report") or []),
            references=dict(raw.get("references") or {}),
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "_note": CATALOG_NOTE,
            "version": CATALOG_VERSION,
            "generated_at": self.generated_at,
            "scenario_file": self.scenario_file,
            "areas": self.areas,
            "datasets": sorted(self.entries, key=lambda e: e["id"]),
            "coverage_report": self.coverage_report,
            "references": self.references,
        }

    def save(self, path: Path) -> None:
        text = json.dumps(self.to_dict(), indent=2, sort_keys=False, ensure_ascii=False) + "\n"
        atomic_write(Path(path), text.encode("utf-8"))

    def get(self, dataset_id: str) -> Dict[str, Any]:
        for e in self.entries:
            if e["id"] == dataset_id:
                return e
        raise KeyError(dataset_id)

    def upsert(self, entry: Dict[str, Any]) -> None:
        for i, e in enumerate(self.entries):
            if e["id"] == entry["id"]:
                self.entries[i] = entry
                return
        self.entries.append(entry)

    def search(
        self,
        words: str = "",
        factor: Optional[str] = None,
        category: Optional[str] = None,
        bounds: Optional[Bounds] = None,
        metric: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        terms = [w.lower() for w in words.split()]
        hits = []
        for e in sorted(self.entries, key=lambda x: x["id"]):
            haystack = " ".join(
                [e.get("id", ""), e.get("title", ""), e.get("summary", "")]
                + [str(t) for t in e.get("tags", [])]
                + [str(t) for t in e.get("limitations", [])]
            ).lower()
            if any(t not in haystack for t in terms):
                continue
            if factor and factor not in e.get("factors", []):
                continue
            if category and e.get("category") != category:
                continue
            if metric:
                from .metrics import metrics_for

                if metric.upper() not in (e.get("metrics") or metrics_for(e["id"])):
                    continue
            if bounds is not None:
                eb = (e.get("coverage") or {}).get("bounds")
                if not eb:
                    continue
                try:
                    if not Bounds.from_list(eb).intersects(bounds):
                        continue
                except ValueError:
                    continue
            hits.append(e)
        return hits

    def check(self, data_root: Path) -> List[CheckResult]:
        results = []
        for e in sorted(self.entries, key=lambda x: x["id"]):
            for rec in e.get("files", []):
                results.append(CheckResult(e["id"], rec["path"], file_state(data_root, rec)))
        return results

    def markdown_table(self) -> str:
        rows = ["| id | what it is | factors | evidence | access |", "|---|---|---|---|---|"]
        for e in sorted(self.entries, key=lambda x: x["id"]):
            access = e.get("access", "")
            if e.get("status") not in (None, "ok"):
                access = f"{access} ({e['status']})"
            rows.append(
                f"| `{e['id']}` | {_md_cell(e.get('summary', ''))} | {_md_cell(', '.join(e.get('factors', [])))} "
                f"| {_md_cell(e.get('evidence_type', ''))} | {_md_cell(access)} |"
            )
        return "\n".join(rows) + "\n"


TABLE_START = "<!-- catalog-table:start -->"
TABLE_END = "<!-- catalog-table:end -->"


METRICS_START = "<!-- metrics:start -->"
METRICS_END = "<!-- metrics:end -->"
REFERENCES_START = "<!-- references:start -->"
REFERENCES_END = "<!-- references:end -->"


def update_doc_table(doc_path: Path, table_md: str, start: str = TABLE_START, end: str = TABLE_END) -> bool:
    """Replace the text between two markers (default: the catalog-table ones); True if the file changed."""
    doc_path = Path(doc_path)
    text = doc_path.read_text(encoding="utf-8")
    i, j = text.find(start), text.find(end)
    if i < 0 or j < 0 or j < i:
        raise CatalogError(f"{doc_path}: missing {start} / {end} markers")
    new = text[: i + len(start)] + "\n" + table_md + text[j:]
    if new == text:
        return False
    atomic_write(doc_path, new.encode("utf-8"))
    return True


